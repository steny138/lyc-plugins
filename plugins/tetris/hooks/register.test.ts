test('I 在兩個方向切換，地板阻擋旋轉時拒絕', async ($, on) => {
  stubEngine(on); mock.clock(on, { now: 36 }); await run($); const ui = await mountPane($)
  for (let i = 0; i < 5; i++) await ui.press({ key: 'down' })
  const before = await board(ui)
  await ui.press({ key: 'rotate' })
  expect((await board(ui)).slice(2, 6)).toEqual(['.....I....', '.....I....', '.....I....', '.....I....'])
  await ui.press({ key: 'rotate' })
  expect(await board(ui)).toEqual(before)
  for (let i = 0; i < 25; i++) await ui.press({ key: 'down' })
  const floor = await board(ui)
  await ui.press({ key: 'rotate' })
  expect(await board(ui)).toEqual(floor)
})
