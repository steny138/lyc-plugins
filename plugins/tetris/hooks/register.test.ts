import { expect, mock, test } from 'claude-code/testing'
import { stubEngine, run, mountPane, board } from './test-support'
test('指令開啟自己的棋盤、下一塊與初始統計', async ($, on) => {
  stubEngine(on)
  mock.clock(on)
  expect((await run($)).text).toContain('已開啟')
  const ui = await mountPane($)
  const raster = await ui.find({ key: 'board' })
  expect(raster.props.columns).toBe(20)
  expect(raster.props.rows).toBe(20)
  expect(await board(ui)).toEqual(Array(20).fill('..........'))
  expect(await ui.find({ type: 'Text', text: /^下一塊：/ })).toBeDefined()
  expect((await ui.find({ type: 'Text', text: '分數：0' })).text).toBe('分數：0')
  expect((await ui.find({ type: 'Text', text: '消行：0' })).text).toBe('消行：0')
  expect((await ui.find({ type: 'Text', text: '等級：0' })).text).toBe('等級：0')
})
test('玩家能下移並左右移動出生區的 L 方塊', async ($, on) => {
  stubEngine(on); mock.clock(on)
  await run($); const ui = await mountPane($)
  for (let i = 0; i < 3; i++) await ui.press({ key: 'down' })
  await ui.press({ key: 'left' })
  expect((await board(ui)).slice(1, 3)).toEqual(['...LLL....', '...L......'])
  await ui.press({ key: 'right' })
  expect((await board(ui)).slice(1, 3)).toEqual(['....LLL...', '....L.....'])
})
test('旋轉 L 方塊採原版逆時針規則', async ($, on) => {
  stubEngine(on); mock.clock(on); await run($); const ui = await mountPane($)
  for (let i = 0; i < 3; i++) await ui.press({ key: 'down' })
  await ui.press({ key: 'rotate' })
  expect((await board(ui)).slice(0, 3)).toEqual(['.....L....', '.....L....', '.....LL...'])
})
test('牆壁與地板拒絕越界', async ($, on) => {
  stubEngine(on); mock.clock(on); await run($); const ui = await mountPane($)
  for (let i = 0; i < 25; i++) await ui.press({ key: 'down' })
  for (let i = 0; i < 15; i++) await ui.press({ key: 'left' })
  expect((await board(ui)).slice(-2)).toEqual(['LLL.......', 'L.........'])
  const before = await board(ui)
  await ui.press({ key: 'down' }); await ui.press({ key: 'left' })
  expect(await board(ui)).toEqual(before)
  for (let i = 0; i < 15; i++) await ui.press({ key: 'right' })
  expect((await board(ui)).slice(-2)).toEqual(['.......LLL', '.......L..'])
})
